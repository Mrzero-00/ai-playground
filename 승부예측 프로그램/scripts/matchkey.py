#!/usr/bin/env python3
"""같은 경기를 가리키는 키 — 회차가 달라도(프로토 ↔ 승무패, 회차 경계) 한 경기로 센다.

왜 (2026-11-17): 집계 스크립트마다 (날짜, 홈, 원정) 전체 이름으로 중복을 걸렀는데, 승무패는 팀명을
4자로 자른다('아이슬란' ↔ '아이슬란드', '보스니아' ↔ '보스니아 헤르체고비나'). 그래서 같은 경기가
프로토 회차와 승무패 회차에서 따로 세어졌다(심층 채점 488경기 중 50경기). 시각 칸도 'MM-DD HH:MM' 과
'YYYY-MM-DD HH:MM' 이 섞여 있어 뒤 11자로 맞춘다.
"""


def key(r):
    # 앞 2자로 맞춘다 — 승무패 약칭은 4자보다 짧을 수도 있다('사우디' ↔ '사우디아라비아'). 4자로 맞추던 첫 판에서
    # 사우디-한국이 두 번 세어졌다. 같은 시각에 홈·원정 앞 2자가 모두 같은 다른 경기는 사실상 없다.
    n = lambda x: (x or "").replace(" ", "")[:2]
    return ((r.get("시각") or "").strip()[-11:], n(r.get("홈")), n(r.get("원정")))
